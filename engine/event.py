"""
event.py
--------
Core event types for the event-driven backtesting engine.

The engine is built around a single FIFO queue of Event objects that
flows through four stages every time step:

    MARKET  ->  SIGNAL  ->  ORDER  ->  FILL

MarketEvent   : "new bar of data has arrived"          (from DataHandler)
SignalEvent   : "a strategy wants to go long/short/flat" (from Strategy)
OrderEvent    : "the portfolio wants to send an order"   (from Portfolio)
FillEvent     : "an order was executed at some price"    (from ExecutionHandler)

Keeping these as distinct, typed events (rather than calling functions
directly) is what makes the engine "event-driven": every component only
reacts to events it pulls off the queue, so there is no way for a
strategy to accidentally see future data (this is what eliminates
look-ahead bias, together with the friction modelling in execution.py).
"""

from dataclasses import dataclass, field
from datetime import datetime
from typing import Optional


class Event:
    """Base class for all events. Never instantiated directly."""
    type: str = "EVENT"


@dataclass
class MarketEvent(Event):
    """A new bar of market data is available for one or more symbols."""
    timestamp: datetime
    type: str = field(default="MARKET", init=False)


@dataclass
class SignalEvent(Event):
    """
    A Strategy has produced a trading signal.

    direction: 'LONG', 'SHORT', or 'EXIT'
    strength : optional conviction score in [0, 1], used for position sizing
    target_weight: optional fraction of equity to hold (e.g. 1/N for an
               equal-weight basket). When set, it replaces volatility-targeted
               sizing; position and leverage caps still apply.
    """
    strategy_id: str
    symbol: str
    timestamp: datetime
    direction: str
    strength: float = 1.0
    target_weight: Optional[float] = None
    type: str = field(default="SIGNAL", init=False)


@dataclass
class OrderEvent(Event):
    """
    A request to trade, generated by the Portfolio in response to a signal.

    order_type: 'MKT' (market order, filled next bar with friction) -- this
                engine only models market orders, which is the conservative
                / standard choice for a backtester since limit fills are
                easy to bias in your own favour.
    quantity  : positive number of shares/contracts
    direction : 'BUY' or 'SELL'
    arrival_price: price observed when the order was decided (the signal
                bar's close) -- the benchmark for implementation shortfall.
    """
    timestamp: datetime
    symbol: str
    order_type: str
    quantity: float
    direction: str
    strategy_id: str = ""
    arrival_price: Optional[float] = None
    type: str = field(default="ORDER", init=False)


@dataclass
class FillEvent(Event):
    """
    An order has actually been executed by the ExecutionHandler.

    fill_price includes slippage. commission and slippage_cost are reported
    separately for transaction cost analysis (TCA).
    """
    timestamp: datetime
    symbol: str
    quantity: float
    direction: str
    fill_price: float
    commission: float
    slippage_cost: float
    latency_bars: int = 0
    strategy_id: str = ""
    type: str = field(default="FILL", init=False)
